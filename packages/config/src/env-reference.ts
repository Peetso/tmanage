export interface EnvReferenceRow {
  readonly name: string;
  readonly required: boolean;
  readonly defaultValue: string | undefined;
  readonly secret: boolean;
  readonly conditional: boolean;
  readonly description: string;
}

/** First sentence of the comment block directly above `    NAME:` in env.ts, or ''. */
function describe(source: string, name: string): string {
  const at = source.search(new RegExp(`^ {4}${name}:`, 'm'));
  if (at < 0) return '';
  const lines = source.slice(0, at).split('\n').slice(0, -1);
  const block: string[] = [];
  for (let i = lines.length - 1; i >= 0; i -= 1) {
    const line = (lines[i] ?? '').trim();
    if (!/^(\/\/|\/\*\*|\*)/.test(line)) break;
    block.unshift(line.replace(/^(\/\/|\/\*\*|\*\/|\*)\s?/, '').replace(/\*\/$/, ''));
    if (line.startsWith('/**')) break; // the nearest doc block only, not the one above it
  }
  // Drop leading plan/finding references ("D09.", "56-02.", "ADR-0001 layer 3.") — they mean
  // nothing to an operator — then keep the first sentence if it says anything.
  const text = block
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^(?:(?:[A-Z]+-?\d[\w-]*(?: layer \d+)?|\d{2}-\d{2}\w*)[.:,]\s*)+/, '');
  // No full stop means a section header ("// Object storage"), not a description.
  const sentence = /^(.+?[.!?])(\s|$)/.exec(text)?.[1] ?? '';
  return sentence.length < 12 ? '' : sentence.replaceAll('|', '\\|');
}

/** One row per schema key; `envSource` is env.ts's text, used for the descriptions only. */
export function envReferenceRows(envSource: string): EnvReferenceRow[] {
  return Object.entries(envSchema.shape).map(([name, field]) => {
    const parsed = (
      field as { safeParse: (v: unknown) => { success: boolean; data?: unknown } }
    ).safeParse(undefined);
    const value = parsed.success ? parsed.data : undefined;
    return {
      name,
      required: !parsed.success,
      defaultValue:
        value === undefined
          ? undefined
          : typeof value === 'object'
            ? JSON.stringify(value)
            : String(value),
      secret: SECRET_ENV_KEYS.has(name),
      conditional: envSource.includes(`fail('${name}'`) || envSource.includes(`['${name}',`),
      description: describe(envSource, name),
    };
  });
}

export function renderEnvReference(envSource: string): string {
  const yes = (b: boolean) => (b ? 'yes' : 'no');
  const rows = envReferenceRows(envSource).map(
    (r) =>
      `| \`${r.name}\` | ${r.required ? 'yes' : 'no'} | ${r.defaultValue === undefined ? '' : `\`${r.defaultValue}\``} | ${yes(r.secret)} | ${r.conditional ? 'yes' : ''} | ${r.description} |`,
  );
  const server = SERVER_ENV.map(([n, s, note]) => `| \`${n}\` | ${yes(s)} | ${note} |`);
  return [
    '# TManage environment reference',
    '',
    '<!-- Generated by `node deploy/self-host/env-reference.mjs` from packages/config/src/env.ts. Do not edit by hand. -->',
    '',
    'Every variable the app validates at start. **Required** means the app will not start without it',
    'in any environment. **Rule** means a cross-field or production check also names it (for example',
    '`SMTP_HOST` when `EMAIL_DRIVER=smtp`, or a secret that must differ from the others); the start-up',
    'error lists every failing variable at once. **Secret** values live only in the env file',
    '(`chmod 600`), are generated, never typed into chat or committed. No real values appear here.',
    '',
    'The single-process server fills `DATABASE_MIGRATION_URL` and `WORKER_DATABASE_URL` from',
    '`DATABASE_URL` (or the `DB_*` parts below) and sets `DATABASE_SINGLE_USER=true` when it is given',
    'one credential, so a one-user install sets only the database connection.',
    '',
    'The single-process server fills `DATABASE_MIGRATION_URL` and `WORKER_DATABASE_URL` from',
    '`DATABASE_URL` (or the `DB_*` parts below) and sets `DATABASE_SINGLE_USER=true` when it is given',
    'one credential, so a one-user install sets only the database connection.',
    '',
    '| Variable | Required | Default | Secret | Rule | What it is |',
    '| --- | --- | --- | --- | --- | --- |',
    ...rows,
    '',
    '## Read by the server process, outside the schema',
    '',
    '| Variable | Secret | What it is |',
    '| --- | --- | --- |',
    ...server,
    '',
  ].join('\n');
}
