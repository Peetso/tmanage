export type PhoneIconName = keyof typeof PATHS;

/**
 * Icons that point along the reading direction. In Arabic (RTL) a menu draws them mirrored;
 * everything else (a sun, a gear, a calendar) reads the same both ways and is never flipped.
 */
export const RTL_MIRRORED_ICONS: ReadonlySet<PhoneIconName> = new Set<PhoneIconName>([
  'back',
  'forward',
  'arrow',
  'send',
  'logOut',
]);

/** Every icon in the set, in the Figma row's order. */
export const PHONE_ICON_NAMES = Object.keys(PATHS) as readonly PhoneIconName[];

export interface PhoneIconProps {
  name: PhoneIconName;
  /** The drawn size in CSS pixels; the design uses 16, 20, 24, 28 and 32. Default 24. */
  size?: number;
  className?: string;
}

function LineIcon({
  name,
  size,
  base,
  className,
  mirror,
}: Required<Omit<PhoneIconProps, 'className'>> & {
  base: string;
  className: string | undefined;
  mirror: boolean;
}) {
  return (
    <svg
      className={className ? `${base} ${className}` : base}
      data-icon={name}
      {...(mirror && RTL_MIRRORED_ICONS.has(name) ? { 'data-mirror': 'rtl' } : {})}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {PATHS[name].map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  );
}

/**
 * Phone surfaces flip their own directional icons in RTL (styles/phone/*.css), so a phone icon
 * carries no mirror marker and is never flipped twice.
 */
export function PhoneIcon({ name, size = 24, className }: PhoneIconProps) {
  return (
    <LineIcon name={name} size={size} base="tm-phone-icon" className={className} mirror={false} />
  );
}

/**
 * A menu entry's icon (R38 G3): the rail, the dock, the More sheet, the portal menus and the
 * Control Center menu. Same set as {@link PhoneIcon}; its own class, so the phone dock's
 * hide/show rules leave it alone; a directional icon is mirrored in RTL (`nav-icon.css`).
 */
export function NavIcon({ name, size = 20, className }: PhoneIconProps) {
  return <LineIcon name={name} size={size} base="tm-nav-icon" className={className} mirror />;
}
