/** Whether the app has its official mark here. Every app does since FIX3 item 9. */
export function hasBrandMark(brand: BrandId): boolean {
  const mark = MARKS[brand];
  return 'path' in mark || 'src' in mark;
}

export interface BrandLogoProps {
  readonly brand: BrandId;
  /** The tile's side in CSS pixels; the mark is half of it, so the clear space is a quarter. */
  readonly size?: 20 | 24 | 32 | 36 | 46;
  /** Only when the tile stands alone: its accessible name. */
  readonly label?: string;
  readonly className?: string;
}

export function BrandLogo({ brand, size = 36, label, className }: BrandLogoProps) {
  const mark = MARKS[brand];
  const a11y = label ? { role: 'img' as const, 'aria-label': label } : { 'aria-hidden': true };
  const classes = ['tm-brand-logo', `tm-brand-logo--${size}`, className].filter(Boolean).join(' ');
  if ('src' in mark) {
    return (
      <span className={classes} data-brand={brand} {...a11y}>
        <img
          className={`tm-brand-logo__mark${mark.padded ? ' tm-brand-logo__mark--padded' : ''}`}
          src={mark.src}
          alt=""
          draggable={false}
        />
      </span>
    );
  }
  return (
    <span className={classes} data-brand={brand} {...a11y}>
      <svg
        className="tm-brand-logo__mark"
        viewBox="0 0 24 24"
        focusable="false"
        aria-hidden="true"
        fill={mark.hex ?? 'currentColor'}
      >
        <path d={mark.path} />
      </svg>
    </span>
  );
}
