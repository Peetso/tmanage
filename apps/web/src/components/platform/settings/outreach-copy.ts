export type OutreachCopyName = keyof typeof OUTREACH_COPY;

export function useOutreachCopy(): (
  name: OutreachCopyName,
  values?: Readonly<Record<string, string | number>>,
) => string {
  const tOr = useTOr();
  return (name, values) => {
    const text = tOr(`PlatformOutreach.${name}`, OUTREACH_COPY[name]);
    return values === undefined ? text : fill(text, values);
  };
}
