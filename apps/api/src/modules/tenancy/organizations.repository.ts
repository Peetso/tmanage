import { eq, isNull, sql, and } from 'drizzle-orm';
import { tenantDrizzle } from '../../common/database/drizzle.js';
import { organizations } from '../../common/database/schema.js';
import type { OrganizationRow } from '../../common/database/schema.js';
import { unwrapQueryError } from '../../common/database/query-error.js';
import type { TenantContext, TenantQueryRunner } from '../../common/database/tenant-context.js';

/**
 * The organization aggregate — TEN-001.
 *
 * Shorter than the other repositories in this module for a structural reason rather than an
 * incidental one: **a context is bound to exactly one organization**, so there is no `list`,
 * no `findById(id)`, and no way to name an organization other than the acting one. The
 * signature is not "which organization?" but "the one you are already in".
 *
 * `organizations` is the one tenant-owned table whose tenant key is `id` rather than
 * `organization_id` (see the guard's registry). That makes an unscoped read of it especially
 * dangerous — a forgotten predicate here lists the customer base — so every statement below
 * anchors on `organizations.id = context.organizationId`.
 *
 * ## Creation is here now, and the note that said it could not be has been replaced
 *
 * That note read: "Provisioning an organization happens before any membership exists, so it
 * cannot run under a `TenantContext` and cannot be a method here." The first half is true and
 * the second turned out not to follow. `ProvisioningService` **generates** the organization's
 * id before the row exists and builds a context around it, so `create` runs under a context
 * bound to exactly the organization it is creating — narrower than any other write in the
 * system, not wider. See that file for the full argument.
 *
 * ## One operation is still deliberately absent
 *
 * **Slug changes.** The slug is in every URL a customer has bookmarked and in every link
 * already sent to their clients. Changing it needs a redirect story and a decision about
 * whether the old slug is reserved or reusable — a product question the planning pack does
 * not answer. Guessing at it here would ship the guess.
 */

export class OrganizationNotFoundError extends Error {
  constructor(readonly organizationId: string) {
    super('The acting organization was not found');
    this.name = 'OrganizationNotFoundError';
  }
}

export class OrganizationVersionConflictError extends Error {
  constructor(readonly organizationId: string) {
    super('The organization was modified concurrently');
    this.name = 'OrganizationVersionConflictError';
  }
}

export interface UpdateOrganizationInput {
  readonly name?: string;
  readonly defaultLocale?: string;
  readonly timezone?: string;
}

/**
 * Raised when the slug is already taken.
 *
 * A distinct error rather than a generic conflict, because it is the one provisioning failure
 * a person can fix themselves — and because the response for it is deliberately different
 * from every other refusal in the identity surface. Telling an unauthenticated caller that a
 * slug exists would enumerate the customer base; telling an **authenticated** person that the
 * address they just typed is taken is the only way they can choose another one, and it
 * reveals nothing they could not learn by visiting the URL.
 */
export class OrganizationSlugTakenError extends Error {
  constructor(readonly slug: string) {
    super('That workspace address is already in use');
    this.name = 'OrganizationSlugTakenError';
  }
}

export interface CreateOrganizationInput {
  /** Generated by the caller, because the context is built around it before the row exists. */
  readonly id: string;
  readonly slug: string;
  readonly name: string;
  readonly defaultLocale: string;
  readonly timezone: string;
}

export class OrganizationsRepository {
  /**
   * Insert the organization this context is bound to.
   *
   * The `id` comes from `input` rather than being generated here, and that is the one
   * departure from every other `create` in this module. It has to: the caller needs the id to
   * build the `TenantContext` that authorises this very statement, so by the time the
   * repository is reached the id is already decided. Passing it in makes that visible instead
   * of hiding a second source of ids inside the transaction.
   *
   * The id is still checked against the context. A caller that generated one id and scoped
   * the transaction to another would otherwise create an organization outside the context
   * that authorised it — the exact thing the guard exists to prevent, arriving through the
   * one door the guard cannot see through.
   */
  async create(
    runner: TenantQueryRunner,
    context: TenantContext,
    input: CreateOrganizationInput,
  ): Promise<OrganizationRow> {
    if (input.id !== context.organizationId) {
      throw new Error(
        'create() was given an id that is not the context it runs under; the row would be ' +
          'outside the tenant scope that authorised it',
      );
    }

    try {
      await tenantDrizzle(runner)
        .insert(organizations)
        .values({
          id: input.id,
          slug: input.slug,
          name: input.name,
          defaultLocale: input.defaultLocale,
          timezone: input.timezone,
          createdAt: sql`current_timestamp(3)`,
          updatedAt: sql`current_timestamp(3)`,
        });
    } catch (error) {
      // `uq_organizations_slug`. Caught by name rather than by attempting a `SELECT` first:
      // the check-then-insert has a race that the unique key does not, and losing that race
      // produces two organizations claiming one address.
      if (isDuplicateSlug(error)) throw new OrganizationSlugTakenError(input.slug);
      throw error;
    }

    return this.requireCurrent(runner, context);
  }

  /** The acting organization, or null if it has since been deleted underneath the session. */
  async findCurrent(
    runner: TenantQueryRunner,
    context: TenantContext,
  ): Promise<OrganizationRow | null> {
    const rows = await tenantDrizzle(runner)
      .select()
      .from(organizations)
      .where(eq(organizations.id, context.organizationId))
      .limit(1);
    return rows[0] ?? null;
  }

  async requireCurrent(
    runner: TenantQueryRunner,
    context: TenantContext,
  ): Promise<OrganizationRow> {
    const found = await this.findCurrent(runner, context);
    if (!found) throw new OrganizationNotFoundError(context.organizationId);
    return found;
  }

  /**
   * Update the acting organization's settings, refusing a stale write.
   *
   * `updated_at` is the concurrency token: `organizations` has no `version` column in
   * `0001_tenancy.sql`. The alternative — adding one — is a migration, and inventing a
   * column here to make the repository tidier is how the schema and its description drift.
   */
  async update(
    runner: TenantQueryRunner,
    context: TenantContext,
    expectedUpdatedAt: Date,
    input: UpdateOrganizationInput,
  ): Promise<OrganizationRow> {
    const changes: Record<string, unknown> = { updatedAt: sql`current_timestamp(3)` };
    if (input.name !== undefined) changes['name'] = input.name;
    if (input.defaultLocale !== undefined) changes['defaultLocale'] = input.defaultLocale;
    if (input.timezone !== undefined) changes['timezone'] = input.timezone;

    const result = await tenantDrizzle(runner)
      .update(organizations)
      .set(changes)
      .where(
        and(
          eq(organizations.id, context.organizationId),
          eq(organizations.updatedAt, expectedUpdatedAt),
        ),
      );

    if (result[0].affectedRows === 0) {
      // No wrong-tenant case to distinguish here: the predicate names the acting
      // organization, so zero rows means either it is gone or the token is stale.
      const current = await this.findCurrent(runner, context);
      if (!current) throw new OrganizationNotFoundError(context.organizationId);
      throw new OrganizationVersionConflictError(context.organizationId);
    }

    return this.requireCurrent(runner, context);
  }

  /**
   * Archive the organization. There is no hard delete.
   *
   * This is the switch that ends access for everyone in the tenant at once: the membership
   * resolver refuses to resolve into an archived organization, so no new `TenantContext` can
   * be built for it and every subsequent request fails at step 2 of the policy sequence. It
   * does not revoke contexts already built — those expire with their sessions, which is why
   * offboarding a *person* is a membership operation and not this one.
   */
  async archive(runner: TenantQueryRunner, context: TenantContext): Promise<OrganizationRow> {
    const result = await tenantDrizzle(runner)
      .update(organizations)
      .set({ archivedAt: sql`current_timestamp(3)`, updatedAt: sql`current_timestamp(3)` })
      .where(and(eq(organizations.id, context.organizationId), isNull(organizations.archivedAt)));

    if (result[0].affectedRows === 0) {
      const current = await this.findCurrent(runner, context);
      if (!current) throw new OrganizationNotFoundError(context.organizationId);
      return current; // Already archived; archiving twice is not an error.
    }

    return this.requireCurrent(runner, context);
  }
}

/**
 * Whether a driver error is the slug unique key.
 *
 * **Unwrapped first**, and that is not defensive coding — it is required. Drizzle wraps
 * anything thrown during execution in a `DrizzleQueryError`, which carries neither `code` nor
 * `errno` and keeps the driver's error on `cause`, and `unwrapQueryError` normally strips
 * that wrapper at the transaction boundary in `TenantDatabase`. This is the first place in
 * the codebase that has to react to a driver error *inside* the transaction, before that
 * boundary is reached, so the unwrapping happens here too. The first run of `ten-001-provisioning.db.test.ts` failed on exactly this: a
 * genuine duplicate-slug error reached the controller as a 500.
 *
 * Matched on the constraint **name** as well as the error code, because `organizations` has
 * exactly one other unique key — the primary key — and a duplicate id would mean the caller
 * generated a colliding UUIDv7, which is not a slug problem and must not be reported as one.
 *
 * The code is matched as the string `ER_DUP_ENTRY`, and the numeric `errno` is not consulted.
 * mysql2 builds every server error in `Packet.asError`, the only place in the driver that
 * assigns `errno`, and it sets `code` from its `ErrorCodeToName` table in the statement
 * immediately before; 1062 has a name in that table, and `unwrapQueryError` returns that same
 * error object — it removes `sql` and nothing else. A duplicate key therefore always arrives
 * with the string.
 */
function isDuplicateSlug(error: unknown): boolean {
  const unwrapped = unwrapQueryError(error);
  if (typeof unwrapped !== 'object' || unwrapped === null) return false;
  const candidate = unwrapped as { code?: unknown; message?: unknown };
  const duplicate = candidate.code === 'ER_DUP_ENTRY';
  const message = typeof candidate.message === 'string' ? candidate.message : '';
  return duplicate && message.includes('uq_organizations_slug');
}
