#!/usr/bin/env node
// CATSPLIT — which message namespaces the public website needs in the browser.
//
//   node scripts/i18n/site-namespaces.mjs        (rewrites apps/web/src/lib/i18n/catalog-app-namespaces.ts)
//
// The browser downloads a language's catalog in two parts: `site` (what the public website and
// the root layout render) and `app` (the rest). This walks the import graph from the website's
// routes and the root layout, collects every namespace any reached file names in a string, and
// lists the namespaces it did NOT reach: those form the `app` part. A namespace nobody has listed
// yet (a new one) therefore lands in `site`, which costs bytes but never shows a raw key.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const WEB = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'apps', 'web');
const SRC = join(WEB, 'src');
const OUTPUT = join(SRC, 'lib', 'i18n', 'catalog-app-namespaces.ts');

/** Where the walk starts: every file of the website routes, and the layouts above them. */
const ROOT_DIRS = ['app/(website)', 'app/ar/(site)'];
const ROOT_FILES = ['app/layout.tsx', 'app/ar/layout.tsx'];
/** Files that name namespaces as data, not as keys (the partial catalog's core list, this list). */
const SKIP = new Set(['lib/i18n/catalog-status.ts', 'lib/i18n/catalog-app-namespaces.ts']);

const IMPORT = /(?:\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)['"]([^'"]+)['"]/gu;
const STRING_HEAD = /['"`]([A-Za-z_][A-Za-z0-9_]*)(?=[.'"`$])/gu;
/** Block comments and whole-line `//` comments: their prose names screens, not keys. */
const COMMENT = /\/\*[\s\S]*?\*\/|^\s*\/\/.*$/gmu;
const EXTENSIONS = ['.ts', '.tsx', '.mjs', '.js', '/index.ts', '/index.tsx'];

function filesUnder(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? filesUnder(path) : [path];
  });
}

function resolveImport(fromFile, specifier) {
  let base;
  if (specifier.startsWith('.')) base = join(dirname(fromFile), specifier);
  else if (specifier.startsWith('@/')) base = join(SRC, specifier.slice(2));
  else return undefined;
  for (const candidate of ['', ...EXTENSIONS]) {
    const path = base + candidate;
    try {
      if (statSync(path).isFile()) return /\.(?:tsx?|mjs|js)$/u.test(path) ? path : undefined;
    } catch {
      // Not this extension; try the next.
    }
  }
  return undefined;
}

/** The namespaces of `en.json` that some file reachable from the website names. */
export function reachedNamespaces(namespaces) {
  const known = new Set(namespaces);
  const queue = [
    ...ROOT_DIRS.flatMap((dir) => filesUnder(join(SRC, dir))).filter((path) =>
      /\.(?:tsx?|mjs|js)$/u.test(path),
    ),
    ...ROOT_FILES.map((file) => join(SRC, file)),
  ];
  const seen = new Set();
  const reached = new Set();
  while (queue.length > 0) {
    const file = queue.pop();
    if (seen.has(file)) continue;
    seen.add(file);
    if (SKIP.has(relative(SRC, file).replaceAll('\\', '/'))) continue;
    const text = readFileSync(file, 'utf8').replace(COMMENT, '');
    for (const match of text.matchAll(STRING_HEAD)) {
      if (known.has(match[1])) reached.add(match[1]);
    }
    for (const match of text.matchAll(IMPORT)) {
      const next = resolveImport(file, match[1]);
      if (next !== undefined && !seen.has(next)) queue.push(next);
    }
  }
  return reached;
}

/** The `app` part: every namespace of `en` the website does not reach, sorted. */
export function appNamespaces(en) {
  const namespaces = [...new Set(Object.keys(en).map((key) => key.split('.')[0] ?? ''))];
  const reached = reachedNamespaces(namespaces);
  return namespaces.filter((namespace) => !reached.has(namespace)).sort();
}

export function renderModule(namespaces) {
  const lines = namespaces.map((namespace) => `  '${namespace}',`).join('\n');
  return `// Generated by scripts/i18n/site-namespaces.mjs; do not edit by hand.
/**
 * CATSPLIT: the namespaces only the signed-in app (not the public website) renders. The browser
 * downloads them as a language's \`app\` part; every other namespace is in its \`site\` part.
 */
export const APP_NAMESPACES: readonly string[] = [
${lines}
];
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const en = JSON.parse(readFileSync(join(SRC, 'lib', 'i18n', 'messages', 'en.json'), 'utf8'));
  const namespaces = appNamespaces(en);
  writeFileSync(OUTPUT, renderModule(namespaces));
  console.log(`${namespaces.length} app namespaces -> ${relative(process.cwd(), OUTPUT)}`);
}
