#!/usr/bin/env node
/**
 * Design-source audit.
 *
 * Cross-references every screen ID declared in the planning pack's whole-app screen
 * matrix (file 41) against the screen IDs that actually appear in the completed
 * `.dc.html` design artifacts.
 *
 * The planning pack is behaviour/security truth. The artifacts plus SESSION-HANDOFF.md
 * are existence/coverage truth. This script exists because parts of the export's own
 * ledger (screen-status.md, design-quality-scorecard.md) are known to be stale.
 *
 * Usage: node scripts/audit-design-source.mjs [--json]
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const matrixPath = join(repoRoot, 'docs/planning/41-WHOLE-APP-SCREEN-AND-STATE-MATRIX.md');
const artifactDir = join(repoRoot, 'docs/design/source/project');

/** Screen IDs look like `PUB-01`, `HOME-03`, `PREF-05`. */
const ID_RE = /\b([A-Z]{2,5})-(\d{2})\b/g;

/** Prefixes that appear in the matrix but are not screen families. */
const NOT_SCREEN_PREFIXES = new Set([
  'WCAG',
  'ISO',
  'SOC',
  'ASVS',
  'UTC',
  'RGB',
  'SHA',
  'AES',
  'TLS',
  'API',
]);

function idsIn(text) {
  const out = new Set();
  for (const m of text.matchAll(ID_RE)) {
    if (NOT_SCREEN_PREFIXES.has(m[1])) continue;
    out.add(`${m[1]}-${m[2]}`);
  }
  return out;
}

/** The matrix declares screens in table rows: `| PUB-01 | Landing | ... |`. */
function declaredScreenIds(matrixText) {
  const ids = [];
  for (const line of matrixText.split('\n')) {
    const m = /^\|\s*([A-Z]{2,5}-\d{2})\s*\|/.exec(line.trim());
    if (m && !NOT_SCREEN_PREFIXES.has(m[1].split('-')[0])) ids.push(m[1]);
  }
  return [...new Set(ids)];
}

const matrixText = readFileSync(matrixPath, 'utf8');
const declared = declaredScreenIds(matrixText);

const artifacts = readdirSync(artifactDir)
  .filter((f) => f.endsWith('.dc.html'))
  .sort();

/** id -> artifact filenames that contain it */
const coverage = new Map(declared.map((id) => [id, []]));
/** artifact -> ids it contains that the matrix declares */
const perArtifact = new Map();

for (const file of artifacts) {
  const text = readFileSync(join(artifactDir, file), 'utf8');
  const found = idsIn(text);
  const relevant = [];
  for (const id of found) {
    if (coverage.has(id)) {
      coverage.get(id).push(file);
      relevant.push(id);
    }
  }
  perArtifact.set(file, relevant.sort());
}

const missing = declared.filter((id) => coverage.get(id).length === 0);
const covered = declared.length - missing.length;

const report = {
  generatedFrom: {
    matrix: 'docs/planning/41-WHOLE-APP-SCREEN-AND-STATE-MATRIX.md',
    artifacts: 'docs/design/source/project/*.dc.html',
  },
  declaredCount: declared.length,
  coveredCount: covered,
  missing,
  artifactCount: artifacts.length,
};

if (process.argv.includes('--json')) {
  console.log(JSON.stringify({ ...report, coverage: Object.fromEntries(coverage) }, null, 2));
  process.exit(missing.length === 0 ? 0 : 1);
}

const lines = [];
lines.push('# Design source audit — screen ID coverage');
lines.push('');
lines.push(
  '> Generated by `node scripts/audit-design-source.mjs`. Do not hand-edit; rerun instead.',
);
lines.push('');
lines.push('## Why this file exists');
lines.push('');
lines.push('The immutable design export ships two ledgers — `design/screens/screen-status.md` and');
lines.push(
  '`design/design-quality-scorecard.md` — that are known to be stale in places (rows still reading',
);
lines.push(
  '`mapped`, "no prototype", or "no tablet composition"). The export itself is treated as immutable,',
);
lines.push(
  'so those ledgers are not corrected in place. This audit is the reconciled coverage truth:',
);
lines.push(
  'it reads the artifacts directly and cross-references them against the screen IDs declared in the',
);
lines.push('planning pack.');
lines.push('');
lines.push('**Precedence recorded here:** the planning pack governs behaviour, authorization, and');
lines.push('security. The `.dc.html` artifacts plus `design/SESSION-HANDOFF.md` govern screen');
lines.push('existence, visual composition, and interaction intent.');
lines.push('');
lines.push('## Result');
lines.push('');
lines.push(`- Screen IDs declared in file 41: **${declared.length}**`);
lines.push(`- Screen IDs present in at least one artifact: **${covered}**`);
lines.push(
  `- Screen IDs with no artifact: **${missing.length}**${missing.length ? ` (${missing.join(', ')})` : ''}`,
);
lines.push(`- \`.dc.html\` artifacts scanned: **${artifacts.length}**`);
lines.push('');
if (missing.length === 0) {
  lines.push(
    '`design/SESSION-HANDOFF.md` records that all declared screen IDs are drawn. This audit',
  );
  lines.push('independently confirms it. There are no missing screen IDs.');
} else {
  lines.push(
    'The following declared screen IDs were not found in any artifact and must be resolved',
  );
  lines.push('with the design owner before the affected features are implemented:');
  lines.push('');
  for (const id of missing) lines.push(`- \`${id}\``);
}
lines.push('');
lines.push('## Screen ID → artifact map');
lines.push('');
lines.push('| Screen ID | Artifact(s) |');
lines.push('|---|---|');
for (const id of declared) {
  const files = coverage.get(id);
  lines.push(
    `| \`${id}\` | ${files.length ? files.map((f) => basename(f, '.dc.html')).join('<br>') : '**— none —**'} |`,
  );
}
lines.push('');
lines.push('## Artifact → screen IDs');
lines.push('');
lines.push('| Artifact | Declared screen IDs present |');
lines.push('|---|---|');
for (const [file, ids] of perArtifact) {
  lines.push(
    `| \`${file}\` | ${ids.length ? ids.map((i) => `\`${i}\``).join(' ') : '_(support/prototype file)_'} |`,
  );
}
lines.push('');
lines.push('## Items that remain genuinely open');
lines.push('');
lines.push(
  'These are human-validation items. They are **not** satisfied by any automated check and',
);
lines.push('must not be marked passed until a person performs them:');
lines.push('');
lines.push('1. Real NVDA and VoiceOver pass over the golden journeys.');
lines.push('2. Native Arabic screen-reader review of the RTL surfaces.');
lines.push('3. Client Portal evidence at 200% browser zoom.');
lines.push('4. Final high-contrast theme verification against the shipped implementation.');
lines.push('');

const outPath = join(repoRoot, 'docs/design/design-source-audit.md');

// Written through Prettier rather than straight to disk.
//
// This file is generated *and* committed *and* read by people, which puts it in the way of
// two gates at once: `pnpm format:check` rejects unaligned Markdown tables, and CI diffs
// this file to prove the committed copy still matches the design export. Emitting text
// Prettier would rewrite made `pnpm audit:design` turn `pnpm format:check` red every time
// it ran — a gate that fails as a consequence of another gate succeeding.
//
// Formatting here, with the repository's own configuration, makes the generator idempotent
// with respect to both. The alternative — adding this path to .prettierignore — would stop
// checking a file that humans read.
const format = await import('prettier');
const formatted = await format.format(lines.join('\n'), {
  ...(await format.resolveConfig(outPath)),
  filepath: outPath,
});
writeFileSync(outPath, formatted, 'utf8');
console.log(
  `design-source-audit: ${covered}/${declared.length} screen IDs covered across ${artifacts.length} artifacts; ${missing.length} missing.`,
);
if (missing.length) console.log(`missing: ${missing.join(', ')}`);
console.log(`wrote ${outPath}`);
process.exit(missing.length === 0 ? 0 : 1);
